// Copies a few familiar surahs from the Quran Investigator prototype's data.js (itself generated from
// tadabbur-for-kids-v1 source-data/quran). Arabic is copied by program, never typed.
// Usage: node extract-quran.mjs ../quran-investigator-prototype/data.js quran.js
import fs from "node:fs";
const [src, out] = process.argv.slice(2);
const window = {};
new Function("window", fs.readFileSync(src, "utf8"))(window);
const KEEP = ["1", "112", "113", "114", "108", "103", "105", "106", "107", "109", "110", "111", "97", "102", "104", "101", "100", "99", "95", "94", "93"];
const order = (id) => KEEP.indexOf(id);
const picked = window.QI_DATA.filter((u) => KEEP.includes(u.id) && !u.passage)
  .sort((a, b) => order(a.id) - order(b.id))
  .map((u) => ({ id: u.id, number: u.number, name: u.name, meaning: u.meaning, ayat: u.ayat.map((a) => ({ n: a.n, text: a.text, words: a.words })) }));
fs.writeFileSync(out, `// Generated by extract-quran.mjs from the Quran Investigator prototype data (tadabbur-for-kids-v1 source-data/quran).\n// Do not edit by hand: the Arabic is copied by program, never typed.\nwindow.LAB_QURAN = ${JSON.stringify(picked)};\n`);
console.log(picked.map((u) => `${u.number} ${u.name} (${u.ayat.length})`).join("\n"));
