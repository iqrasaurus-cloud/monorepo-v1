// Copies the dino pose library from the tools repo into packages/ui and writes its data file.
//
//   node scripts/sync-mascots.mjs [path/to/tadabbur-for-kids-v1]
//
// The poses are the owner's artwork, cut from the pose sheets in the tools repo
// (packages/design/assets/mascots). They are only copied here, never redrawn or recoloured
// (CLAUDE.md rule 9). Run again whenever the library there changes.
import fs from 'node:fs'
import path from 'node:path'

const root = path.join(import.meta.dirname, '..')
const tools = path.resolve(process.argv[2] ?? path.join(root, '../tadabbur-for-kids-v1'))
const from = path.join(tools, 'packages/design/assets/mascots')
const to = path.join(root, 'packages/ui/assets/mascots')
const dataFile = path.join(root, 'packages/ui/src/mascot/mascot-data.ts')

if (!fs.existsSync(path.join(from, 'manifest.json'))) {
  console.error(`No mascot library at ${from}. Pass the tools repo path as the first argument.`)
  process.exit(1)
}

const manifest = JSON.parse(fs.readFileSync(path.join(from, 'manifest.json'), 'utf8'))
fs.rmSync(to, { recursive: true, force: true })
fs.mkdirSync(to, { recursive: true })

for (const pose of manifest) {
  for (const size of ['sm', 'md', 'lg']) {
    const file = pose.sizes[size].file
    fs.copyFileSync(path.join(from, file), path.join(to, file))
  }
}

// Plain imports, so Vite gives the same URL in dev, while pre-rendering and in the build.
const id = (file) => file.replace(/\.webp$/, '').replace(/-(\w)/g, (_, c) => c.toUpperCase())
const names = manifest.map((p) => p.name)
const files = manifest.flatMap((p) => ['sm', 'md', 'lg'].map((size) => p.sizes[size].file))
const lines = [
  '// Generated by scripts/sync-mascots.mjs from the tools repo. Do not edit by hand.',
  '',
  ...files.map((f) => `import ${id(f)} from '../../assets/mascots/${f}'`),
  '',
  '/** Every pose in the dino library. */',
  `export const POSE_NAMES = ${JSON.stringify(names)} as const`,
  'export type PoseName = (typeof POSE_NAMES)[number]',
  '',
  '/** Per pose: [sm width, md width, lg width, md height, label]. */',
  'export const POSES: Record<PoseName, readonly [number, number, number, number, string]> = {',
  ...manifest.map(
    (p) =>
      `  ${JSON.stringify(p.name)}: [${p.sizes.sm.width}, ${p.sizes.md.width}, ${p.sizes.lg.width}, ${p.sizes.md.height}, ${JSON.stringify(p.label)}],`,
  ),
  '}',
  '',
  '/** Per pose: the sm, md and lg image URLs. Vite copies them into each build. */',
  'export const POSE_URLS: Record<PoseName, readonly [string, string, string]> = {',
  ...manifest.map(
    (p) =>
      `  ${JSON.stringify(p.name)}: [${id(p.sizes.sm.file)}, ${id(p.sizes.md.file)}, ${id(p.sizes.lg.file)}],`,
  ),
  '}',
  '',
]
fs.mkdirSync(path.dirname(dataFile), { recursive: true })
fs.writeFileSync(dataFile, lines.join('\n'))
console.log(
  `Copied ${manifest.length} poses to ${path.relative(root, to)} and wrote ${path.relative(root, dataFile)}`,
)
